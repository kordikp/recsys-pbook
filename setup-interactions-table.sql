-- The one event table of the p-book engine. Run it in the Supabase SQL editor of a NEW project
-- (an existing project already has it: compare before you change anything).
-- Readers' events come through /api/log; wallet, galleries, proposals and failed logins are rows
-- written by their own functions (see SECURITY.md). Columns are what api/*.js read and write.

CREATE TABLE IF NOT EXISTS interactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id text,            -- reader-… (device), acct-… (account), an e-mail (wallet), deck:/draft:/auth:… (server rows)
  type text NOT NULL,      -- event, detailview, rating, wallet, deck, draft, proposal, profile, …
  event text,              -- mode_switch, boss_graded, wallet_earn, profile_summary, …
  item_id text,
  mode text,
  duration double precision,
  rating double precision,
  data jsonb,              -- the whole row as sent (book, lang, classCode, …)
  server_ts bigint
);

CREATE INDEX IF NOT EXISTS idx_interactions_created ON interactions (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_interactions_event_user ON interactions (event, user_id);
CREATE INDEX IF NOT EXISTS idx_interactions_type ON interactions (type);
CREATE INDEX IF NOT EXISTS idx_interactions_data_id ON interactions ((data->>'id'));
CREATE INDEX IF NOT EXISTS idx_interactions_data_group ON interactions ((data->>'group'));

-- Only the serverless functions may read or write: they use the service_role key, which
-- bypasses RLS. With RLS on and no policy, the public anon key reads nothing.
ALTER TABLE interactions ENABLE ROW LEVEL SECURITY;
