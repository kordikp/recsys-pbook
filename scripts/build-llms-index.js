#!/usr/bin/env node
// Regenerates the chapter + concept index in llms.txt from content/book.json and
// content/concepts.json, so AI answer engines can find and cite each concept:
// its anchor as raw markdown, the question it answers, and its in-app link.
//
// Only the region between the concept-index markers is rewritten; the rest of
// llms.txt stays hand-written. Concepts whose anchor is not published
// (status other than accepted) are left out. Idempotent.
// Run after scripts/migrate-facets.js:  node scripts/build-llms-index.js [--check]

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://recsys-pbook.vercel.app';
const LLMS = path.join(ROOT, 'llms.txt');
const START = '<!-- concept-index:start';
const END = '<!-- concept-index:end -->';

const book = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/book.json'), 'utf8'));
const concepts = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/concepts.json'), 'utf8')).concepts || [];

function frontmatterKey(file, key) {
  try {
    const m = fs.readFileSync(file, 'utf8').match(/^---\n([\s\S]*?)\n---/);
    const s = m && m[1].match(new RegExp(`^${key}:\\s*(.*)$`, 'm'));
    return s ? s[1].trim().replace(/^["']|["']$/g, '') : null;
  } catch (e) { return 'missing'; }
}
const frontmatterStatus = file => frontmatterKey(file, 'status');
// block id → content-relative path (a chapter without a -spine- file has a
// concept whose anchor is a satellite, and concepts.json then has no anchorPath)
const pathOfId = new Map();
for (const ch of book.chapters) {
  for (const f of ch.files) pathOfId.set(frontmatterKey(path.join(ROOT, 'content', ch.directory, f), 'id'), `${ch.directory}/${f}`);
}
const published = status => !status || status === 'accepted';
// concepts.json carries some literal backslash-escaped quotes; print them plainly
const clean = s => String(s || '').replace(/\\+"/g, '"').replace(/\s+/g, ' ').trim();

let blocks = 0;
const lines = [];
for (const ch of book.chapters) {
  for (const f of ch.files) {
    if (published(frontmatterStatus(path.join(ROOT, 'content', ch.directory, f)))) blocks++;
  }
}
const listed = [];
for (const ch of book.chapters) {
  lines.push('', `### Chapter ${ch.number}: ${ch.title}`, ch.subtitle || '');
  for (const c of concepts.filter(c => c.chapter === ch.id)) {
    const anchorPath = c.anchorPath || pathOfId.get(c.anchor);
    if (!anchorPath || !published(frontmatterStatus(path.join(ROOT, 'content', anchorPath)))) continue;
    const q = clean(c.contract && c.contract.recallQ);
    lines.push(`- [${clean(c.title)}](${SITE}/content/${anchorPath})${q ? `: ${q}` : ''} (in the app: ${SITE}/#c/${c.id})`);
    listed.push(c.id);
  }
}

const region = [
  `${START} — generated by scripts/build-llms-index.js from content/book.json and content/concepts.json; do not edit by hand -->`,
  `${book.chapters.length} chapters, ${listed.length} concepts, ${blocks} published content blocks. Each concept links its anchor telling as raw markdown, the question a reader can answer after reading it, and its page in the app (other tellings of the same concept are listed in /content/concepts.json).`,
  ...lines,
  '',
  END,
].join('\n');

const text = fs.readFileSync(LLMS, 'utf8');
const a = text.indexOf(START);
const b = text.indexOf(END);
if (a === -1 || b === -1 || b < a) {
  console.error('llms.txt has no concept-index markers — add them where the index should go');
  process.exit(1);
}
const next = text.slice(0, a) + region + text.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('llms.txt concept index is stale — run node scripts/build-llms-index.js'); process.exit(1); }
  console.log('llms.txt concept index is up to date');
} else {
  fs.writeFileSync(LLMS, next);
  console.log(`llms.txt: ${listed.length} concepts in ${book.chapters.length} chapters, ${blocks} published blocks`);
}
